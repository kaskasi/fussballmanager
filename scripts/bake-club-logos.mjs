#!/usr/bin/env node
/**
 * Copy assets/club_logos → public/assets/club-logos/logo-NNN.svg (stable sort).
 * Writes src/ui/assets/club-logo-catalog.ts for the client bundle.
 */
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "assets/club_logos");
const outDir = join(root, "public/assets/club-logos");
const catalogTs = join(root, "src/ui/assets/club-logo-catalog.ts");

mkdirSync(outDir, { recursive: true });

const files = readdirSync(srcDir)
  .filter((name) => name.toLowerCase().endsWith(".svg"))
  .sort((a, b) => a.localeCompare(b, "en"));

const slugs = files.map((_, index) => {
  const slug = `logo-${String(index).padStart(3, "0")}.svg`;
  copyFileSync(join(srcDir, files[index]), join(outDir, slug));
  return slug;
});

const body = `/** Generated by npm run bake:club-logos — do not edit by hand. */

export const CLUB_LOGO_COUNT = ${slugs.length};

export const CLUB_LOGO_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)} as const;

export function clubLogoPublicPath(index: number): string {
  const slug = CLUB_LOGO_SLUGS[((index % CLUB_LOGO_COUNT) + CLUB_LOGO_COUNT) % CLUB_LOGO_COUNT];
  return \`/assets/club-logos/\${slug}\`;
}
`;

writeFileSync(catalogTs, body, "utf8");
console.log(`Baked ${slugs.length} club logos + catalog`);
